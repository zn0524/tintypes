import 'dart:io';
import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';
import 'package:image_picker/image_picker.dart';

import 'services/image_detector.dart';

class ImageCheckerScreen extends StatefulWidget {
  const ImageCheckerScreen({super.key});

  @override
  State<ImageCheckerScreen> createState() => _ImageCheckerScreenState();
}

class _ImageCheckerScreenState extends State<ImageCheckerScreen> {
  File? _selectedImage;
  String _aiPercentage = '--%';
  String _realPercentage = '--%';
  final ImagePicker _picker = ImagePicker();

  @override
  void initState() {
    super.initState();
    // Warm up the model while the screen opens
    ImageDetector.instance.initialize();
  }

  Future<void> _pickImage(ImageSource source) async {
    final XFile? image = await _picker.pickImage(source: source);
    if (image == null) return;

    setState(() {
      _selectedImage = File(image.path);
      _aiPercentage = '...';
      _realPercentage = '...';
    });

    try {
      final result = await ImageDetector.instance.detect(image.path);
      if (!mounted) return;
      setState(() {
        _aiPercentage = result.aiPercent;
        _realPercentage = result.realPercent;
      });
    } catch (e) {
      if (!mounted) return;
      setState(() {
        _aiPercentage = '--%';
        _realPercentage = '--%';
      });
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('Could not analyze image: $e')),
      );
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: const Color(0xFF051F20),
      appBar: AppBar(
        title: Text(
          'Check an Image',
          style: GoogleFonts.outfit(
            fontSize: 20,
            fontWeight: FontWeight.w700,
            letterSpacing: 1.5,
            color: const Color(0xFFdaf1de),
          ),
        ),
        backgroundColor: const Color(0xFF051F20),
        elevation: 0,
        iconTheme: const IconThemeData(color: Color(0xFF8EB69B)),
      ),
      body: Padding(
        padding: const EdgeInsets.all(20.0),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            // Instruction text blurb
            Text(
              'Upload an image from your photos or take a new picture to check if it was likely generated by AI.',
              style: GoogleFonts.outfit(
                color: const Color(0xFFdaf1de),
                fontSize: 14,
                height: 1.4,
              ),
            ),
            const SizedBox(height: 20),

            // Image Preview Container
            Expanded(
              child: Container(
                decoration: BoxDecoration(
                  color: const Color(0xFF0B2B2C),
                  borderRadius: BorderRadius.circular(16),
                  border: Border.all(
                    color: const Color(0xFF8EB69B).withOpacity(0.3),
                  ),
                ),
                child: _selectedImage != null
                    ? ClipRRect(
                        borderRadius: BorderRadius.circular(16),
                        child: Image.file(
                          _selectedImage!,
                          fit: BoxFit.cover,
                          width: double.infinity,
                        ),
                      )
                    : Center(
                        child: Column(
                          mainAxisAlignment: MainAxisAlignment.center,
                          children: [
                            const Icon(
                              Icons.image_outlined,
                              size: 48,
                              color: Color(0xFF8EB69B),
                            ),
                            const SizedBox(height: 10),
                            Text(
                              'No image selected',
                              style: GoogleFonts.outfit(
                                color: const Color(0xFF8EB69B).withOpacity(0.7),
                                fontSize: 16,
                              ),
                            ),
                          ],
                        ),
                      ),
              ),
            ),
            const SizedBox(height: 20),

            // Action Buttons (Take a Picture & Upload)
            Row(
              children: [
                Expanded(
                  child: ElevatedButton.icon(
                    onPressed: () => _pickImage(ImageSource.camera),
                    icon: const Icon(Icons.camera_alt, size: 20),
                    label: Text(
                      'Take Picture',
                      style: GoogleFonts.outfit(
                        fontSize: 15,
                        fontWeight: FontWeight.w700,
                      ),
                    ),
                    style: ElevatedButton.styleFrom(
                      backgroundColor: const Color(0xFF8EB69B),
                      foregroundColor: const Color(0xFF051F20),
                      padding: const EdgeInsets.symmetric(vertical: 14),
                      shape: RoundedRectangleBorder(
                        borderRadius: BorderRadius.circular(12),
                      ),
                      elevation: 0,
                    ),
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: ElevatedButton.icon(
                    onPressed: () => _pickImage(ImageSource.gallery),
                    icon: const Icon(Icons.photo_library, size: 20),
                    label: Text(
                      'Upload',
                      style: GoogleFonts.outfit(
                        fontSize: 15,
                        fontWeight: FontWeight.w700,
                      ),
                    ),
                    style: ElevatedButton.styleFrom(
                      backgroundColor: const Color(0xFF8EB69B),
                      foregroundColor: const Color(0xFF051F20),
                      padding: const EdgeInsets.symmetric(vertical: 14),
                      shape: RoundedRectangleBorder(
                        borderRadius: BorderRadius.circular(12),
                      ),
                      elevation: 0,
                    ),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 20),

            // Results section displaying AI and Real percentages
            Container(
              padding: const EdgeInsets.all(16),
              decoration: BoxDecoration(
                color: const Color(0xFF0B2B2C),
                borderRadius: BorderRadius.circular(12),
                border: Border.all(
                  color: const Color(0xFF8EB69B).withOpacity(0.3),
                ),
              ),
              child: Row(
                mainAxisAlignment: MainAxisAlignment.spaceAround,
                children: [
                  Text(
                    'AI: $_aiPercentage',
                    style: GoogleFonts.outfit(
                      fontSize: 18,
                      fontWeight: FontWeight.w600,
                      color: const Color(0xFFdaf1de),
                    ),
                  ),
                  Container(
                    height: 24,
                    width: 1,
                    color: const Color(0xFF8EB69B).withOpacity(0.5),
                  ),
                  Text(
                    'Real: $_realPercentage',
                    style: GoogleFonts.outfit(
                      fontSize: 18,
                      fontWeight: FontWeight.w600,
                      color: const Color(0xFFdaf1de),
                    ),
                  ),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }
}